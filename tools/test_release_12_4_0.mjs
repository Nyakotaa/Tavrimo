import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = path => fs.readFileSync(new URL(path, import.meta.url), 'utf8');
const app = read('../app.js');
const html = read('../index.html');
const css = read('../spotify-dark.css');
const sw = read('../sw.js');
const manifest = JSON.parse(read('../RELEASE_MANIFEST.json'));
const version = read('../VERSION').trim();
assert.equal(version, '12.4.0');
assert.ok(app.includes("const APP_VERSION = '12.4.0'"));
assert.ok(app.includes('const SCHEMA_VERSION = 17'));
assert.ok(app.includes("const STORAGE_KEY = 'tavrimo-planner-v17'"));
assert.equal(manifest.version, version);
assert.equal(manifest.release, version);
assert.ok(html.includes('id="appVersionLabel">v12.4.0</span>'));
for (const resource of ['app.js', 'style.css', 'spotify-dark.css', 'calendar-update.css', 'config.js']) assert.ok(html.includes(resource + '?v=12.4.0'), 'Missing cache-bust for ' + resource);
assert.ok(sw.includes('tavrimo-v12.4.0-'));
assert.ok(html.includes('id="startupSplash"'));
assert.ok(html.includes('assets/branding/tavrimo-cup-mark.png'));
assert.ok(css.includes('.startup-splash__progress-fill'));
assert.ok(app.includes('function finishStartupSplash'));
assert.ok(css.includes('.topbar-context'));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(ids.length, new Set(ids).size, 'HTML IDs must be unique');
const idSet = new Set(ids);
const bindings = new RegExp("\\$\\('#([A-Za-z0-9_-]+)'\\)\\.(?:addEventListener|onclick|onchange|onsubmit)", 'g');
for (const match of app.matchAll(bindings)) assert.ok(idSet.has(match[1]), 'Missing HTML element for event binding #' + match[1]);
for (const view of ['today', 'calendar', 'tasks', 'more', 'profile']) assert.ok(html.includes('data-view="' + view + '"'), 'Missing view ' + view);
for (const token of ['calendar-mode', 'universityCalendarPanel', 'calendarManagerBackdrop', 'universitySetupBackdrop', 'displayNameInput', 'brand-wordmark']) assert.equal(html.includes(token), false, 'Legacy UI element remains: ' + token);
for (const id of ['profileAvatarInput', 'profileStatsBtn', 'profileHealthBtn', 'todayIcsInput']) assert.ok(html.includes('id="' + id + '"'));
console.log('Tavrimo 12.4.0 release/UI structure tests passed.');
